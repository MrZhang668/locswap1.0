"""Product corpus for the large-scale mock dataset.

DATA ONLY, no logic -- the generation logic lives in seed_mock.py.

The corpus is organized by the 9 categories in config.CATEGORY_DICT; brands come
from config.BRAND_DICT, colors from COLOR_DICT and conditions from CONDITION_DICT,
so the structured-recall leg has something to match against.

Each "product prototype" is a 7-tuple:

    (base, brands, variants, (price_lo, price_hi), colors, specs, uses)

    base     the head noun of the product, e.g. "机械键盘"
    brands   brand candidates; None means "no brand / generic", and repeating an
             entry raises its pick probability
    variants spec variants that go into the item name, e.g. "87 键无数字区"
    price    price range in USD; the actual value is drawn from the range and
             snapped to a "human" price
    colors   color candidates that make sense for the prototype
    specs    detail clauses that go into the description -- at least 4 per
             prototype to keep the copy from feeling templated; plain ASCII
             commas only (seed_mock takes spec.split(",")[0] for summaries)
    uses     purpose / scenario clauses for the summary and description tail
"""

